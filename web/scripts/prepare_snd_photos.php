<?php

/**
 * @file
 * Prepare the Spruce Needle Drop photos for publication.
 *
 * Three things have to happen to a phone photo before it goes on a public
 * page, and none of them are cosmetic:
 *
 * 1. ⚠ STRIP EXIF — these carry GPS COORDINATES. The copy brief says "the
 *    images do not identify the property", which is true of what you can SEE
 *    in them and false of what is embedded in them: a GPS tag pins the exact
 *    location of somebody's home. Re-encoding through GD drops all EXIF, which
 *    is the point, not a side effect.
 *
 * 2. ⚠ BAKE IN THE ORIENTATION — the whole-tree shot has EXIF Orientation 6
 *    (rotate 90° CW). Drupal image-style derivatives do NOT honour EXIF
 *    orientation, so it would render on its side; this is a known BOS gotcha.
 *    Rotating the pixels and then discarding the tag makes the file correct
 *    without depending on anything downstream reading it.
 *
 * 3. RESIZE — the originals are 6–9 MB each at 4000px. Five of those is ~40 MB
 *    on one page, and every derivative is generated by PHP on a box whose
 *    binding limit is 1 GB. 2560px is beyond any display size on the site.
 *
 * Writes <name>.web.jpg beside each source; never overwrites an original.
 *
 * Run: ddev exec php web/scripts/prepare_snd_photos.php
 */

$dir = __DIR__ . '/tmp_snd';
$maxDim = 2560;
$quality = 82;

printf("gd=%s exif=%s\n\n", extension_loaded('gd') ? 'yes' : 'NO', function_exists('exif_read_data') ? 'yes' : 'NO');
printf("%-30s %-13s %-8s %-5s %-9s %s\n", 'FILE', 'SOURCE', 'GPS', 'ORI', 'OUT', 'SAVED');
printf("%s\n", str_repeat('-', 86));

foreach (glob($dir . '/*.jpg') as $path) {
  if (str_contains($path, '.web.jpg')) {
    continue;
  }
  $exif = @exif_read_data($path);
  $hasGps = $exif && (isset($exif['GPSLatitude']) || isset($exif['GPSLongitude']));
  $orientation = (int) ($exif['Orientation'] ?? 1);
  [$w, $h] = getimagesize($path);
  $srcBytes = filesize($path);

  $im = imagecreatefromjpeg($path);
  if (!$im) {
    printf("%-30s ** could not decode **\n", basename($path));
    continue;
  }

  // Bake the orientation into the pixels.
  $im = match ($orientation) {
    3 => imagerotate($im, 180, 0),
    6 => imagerotate($im, -90, 0),
    8 => imagerotate($im, 90, 0),
    default => $im,
  };
  $w = imagesx($im);
  $h = imagesy($im);

  // Resize the long edge down to $maxDim.
  if (max($w, $h) > $maxDim) {
    $scale = $maxDim / max($w, $h);
    $nw = (int) round($w * $scale);
    $nh = (int) round($h * $scale);
    $dst = imagecreatetruecolor($nw, $nh);
    imagecopyresampled($dst, $im, 0, 0, 0, 0, $nw, $nh, $w, $h);
    imagedestroy($im);
    $im = $dst;
    $w = $nw;
    $h = $nh;
  }

  $out = preg_replace('/\.jpg$/', '.web.jpg', $path);
  imagejpeg($im, $out, $quality);
  imagedestroy($im);

  // Confirm the EXIF really is gone rather than assuming the re-encode did it.
  $outExif = @exif_read_data($out);
  $stillGps = $outExif && (isset($outExif['GPSLatitude']) || isset($outExif['GPSLongitude']));

  printf("%-30s %5dx%-7d %-8s %-5d %5dx%-4d %5.1f -> %4.1f MB %s\n",
    basename($out), ...[
      0 => (int) (getimagesize($path)[0]),
      1 => (int) (getimagesize($path)[1]),
      2 => $hasGps ? 'STRIPPED' : 'none',
      3 => $orientation,
      4 => $w,
      5 => $h,
      6 => $srcBytes / 1048576,
      7 => filesize($out) / 1048576,
      8 => $stillGps ? '** GPS SURVIVED — DO NOT PUBLISH **' : '',
    ]);
}
